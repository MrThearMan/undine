from __future__ import annotations

from typing import TYPE_CHECKING, Any, Protocol

if TYPE_CHECKING:
    from collections.abc import Collection, Iterable, Iterator, Mapping

    from django.db.models import Model, QuerySet


class ModelManager[T: Model](Protocol):  # noqa: PLR0904
    """Protocol of a model manager."""

    def get_queryset(self) -> QuerySet[T]: ...

    def iterator(self, chunk_size: int | None = None) -> Iterator[T]: ...

    def aggregate(self, *args: Any, **kwargs: Any) -> dict[str, Any]: ...

    def count(self) -> int: ...

    def get(self, *args: Any, **kwargs: Any) -> T: ...

    def create(self, **kwargs: Any) -> T: ...

    def bulk_create(  # noqa: PLR0917
        self,
        objs: Iterable[T],
        batch_size: int | None = None,
        ignore_conflicts: bool = False,  # noqa: FBT001, FBT002
        update_conflicts: bool = False,  # noqa: FBT001, FBT002
        update_fields: Collection[str] | None = None,
        unique_fields: Collection[str] | None = None,
    ) -> list[T]: ...

    def bulk_update(
        self,
        objs: Iterable[T],
        fields: Collection[str],
        batch_size: int | None = None,
    ) -> int: ...

    def get_or_create(
        self,
        defaults: Mapping[str, Any] | None = None,
        **kwargs: Any,
    ) -> tuple[T, bool]: ...

    def update_or_create(
        self,
        defaults: Mapping[str, Any] | None = None,
        create_defaults: Mapping[str, Any] | None = None,
        **kwargs: Any,
    ) -> tuple[T, bool]: ...

    def first(self) -> T | None: ...

    def last(self) -> T | None: ...

    def delete(self) -> int: ...

    def update(self, **kwargs: Any) -> int: ...

    def exists(self) -> bool: ...

    def contains(self, obj: T) -> bool: ...

    def values(self, *fields: str, **expressions: Any) -> QuerySet[T]: ...

    def values_list(self, *fields: str, flat: bool = False, named: bool = False) -> QuerySet[T]: ...

    def none(self) -> QuerySet[T]: ...

    def all(self) -> QuerySet[T]: ...

    def filter(self, *args: Any, **kwargs: Any) -> QuerySet[T]: ...

    def exclude(self, *args: Any, **kwargs: Any) -> QuerySet[T]: ...

    def union(self, *other_qs: QuerySet[T], all: bool = False) -> QuerySet[T]: ...  # noqa: A002

    def intersection(self, *other_qs: QuerySet[T]) -> QuerySet[T]: ...

    def difference(self, *other_qs: QuerySet[T]) -> QuerySet[T]: ...

    def select_related(self, *fields: Any) -> QuerySet[T]: ...

    def prefetch_related(self, *lookups: Any) -> QuerySet[T]: ...

    def annotate(self, *args: Any, **kwargs: Any) -> QuerySet[T]: ...

    def alias(self, *args: Any, **kwargs: Any) -> QuerySet[T]: ...

    def order_by(self, *field_names: Any) -> QuerySet[T]: ...

    def distinct(self, *field_names: Any) -> QuerySet[T]: ...

    def reverse(self) -> QuerySet[T]: ...

    def defer(self, *fields: Any) -> QuerySet[T]: ...

    def only(self, *fields: Any) -> QuerySet[T]: ...

    def using(self, alias: str | None) -> QuerySet[T]: ...


class RelatedManager[T: Model](ModelManager, Protocol):
    """Protocol of a manager for one-to-many and many-to-many relations."""

    def add(self, *objs: T, bulk: bool = True) -> int: ...

    def set(
        self,
        objs: Iterable[T],
        *,
        clear: bool = False,
        through_defaults: Any = None,
    ) -> QuerySet[T]: ...

    def clear(self) -> None: ...

    def remove(self, obj: Iterable[T], bulk: bool = True) -> T: ...  # noqa: FBT001, FBT002

    def create(self, through_defaults: Any = None, **kwargs: Any) -> T: ...
