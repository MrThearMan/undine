from __future__ import annotations

import io
from textwrap import dedent
from unittest.mock import patch

import pytest
from django.core.management import CommandError, call_command

from example_project.app.models import Task
from undine import Entrypoint, Field, Input, MutationType, QueryType, RootType, create_schema

from . import correct_marker_module, incorrect_marker_module


def test_generate_file_end_to_end__success(undine_settings):
    class TaskType(QueryType[Task]):
        name = Field()

    class TaskCreateMutation(MutationType[Task], auto=False):
        name = Input(required=True)

    class Query(RootType):
        task = Entrypoint(TaskType)

    class Mutation(RootType):
        task_mutation = Entrypoint(TaskCreateMutation)

    undine_settings.SCHEMA = create_schema(query=Query, mutation=Mutation)
    undine_settings.MUTATION_INPUT_DATA_TYPES_MODULE = correct_marker_module.__name__

    out = dedent("""\
        # Generated by undine. DO NOT EDIT. Regenerate with `python manage.py generate_mutation_input_types`.
        from __future__ import annotations

        from typing import TypedDict


        class TaskCreateMutationFullInputData(TypedDict):
            name: str


        class TaskCreateMutationInputData(TypedDict):
            name: str
    """)

    stdout = io.StringIO()

    with (
        patch("pathlib.Path.mkdir") as mkdir_patch,
        patch("pathlib.Path.write_text") as write_patch,
        patch("pathlib.Path.unlink"),
    ):
        call_command("generate_mutation_input_types", stdout=stdout)

    assert mkdir_patch.call_count == 1
    assert mkdir_patch.call_args.kwargs["exist_ok"] is True
    assert mkdir_patch.call_args.kwargs["parents"] is True

    assert write_patch.call_count == 1
    assert write_patch.call_args.args[0] == out
    assert write_patch.call_args.kwargs["encoding"] == "utf-8"

    assert stdout.getvalue() == f"Wrote {correct_marker_module.__file__}\n"


def test_generate_file_end_to_end__failure(undine_settings):
    class TaskType(QueryType[Task]):
        name = Field()

    class TaskCreateMutation(MutationType[Task], auto=False):
        name = Input(required=True)

    class Query(RootType):
        task = Entrypoint(TaskType)

    class Mutation(RootType):
        task_mutation = Entrypoint(TaskCreateMutation)

    undine_settings.SCHEMA = create_schema(query=Query, mutation=Mutation)
    undine_settings.MUTATION_INPUT_DATA_TYPES_MODULE = incorrect_marker_module.__name__

    with (
        patch("pathlib.Path.mkdir"),
        patch("pathlib.Path.write_text"),
        patch("pathlib.Path.unlink"),
        pytest.raises(CommandError, match="Refusing to overwrite"),
    ):
        call_command("generate_mutation_input_types", stdout=io.StringIO())


def test_generate_file_end_to_end__no_mutation_types(undine_settings) -> None:
    class TaskType(QueryType[Task]):
        name = Field()

    class Query(RootType):
        task = Entrypoint(TaskType)

    undine_settings.SCHEMA = create_schema(query=Query)
    undine_settings.MUTATION_INPUT_DATA_TYPES_MODULE = correct_marker_module.__name__

    stdout = io.StringIO()

    with (
        patch("pathlib.Path.mkdir"),
        patch("pathlib.Path.write_text"),
        patch("pathlib.Path.unlink") as unlink_patch,
    ):
        call_command("generate_mutation_input_types", stdout=stdout)

    assert unlink_patch.call_count == 1
    assert unlink_patch.call_args.kwargs["missing_ok"] is True

    assert stdout.getvalue() == f"No MutationTypes found in schema\nRemoving {correct_marker_module.__file__}\n"
